"""Draw the Seagalia lockup in braille and inline it into install.sh as its banner.

Same drawing as flock's dev banner: one braille dot per pixel of the logo rendered 160px wide, so 80 columns in the
terminal. Each pixel is snapped to the logo's own palette and a character takes its most common color, so details do
not blur into in-between colors and runs of the same color share one escape code, which keeps install.sh small.

Needs rsvg-convert. Usage: python3 scripts/banner.py install.sh
"""
import collections, re, struct, subprocess, sys, zlib

WIDTH = 160
BIRD_BLUE = "#0B8FDE"
# The navy of the eyes is barely visible on a dark terminal, and one braille character can only hold one color, so on the
# dark banner the eyes are drawn as gaps that let the dark background show through.
EYE_NAVY = (0x0B, 0x2F, 0x55)
LOGOS = {
    "BANNER_DARK": ("assets/logos/seagalia-lockup-dark.svg", {EYE_NAVY}),
    "BANNER_LIGHT": ("assets/logos/seagalia-lockup.svg", set()),
}
# bits of the dots of a braille character, by row then column
BRAILLE_DOTS = [[0x01, 0x08], [0x02, 0x10], [0x04, 0x20], [0x40, 0x80]]


def paeth(left, up, up_left):
    """Pick the neighbour closest to left + up - up_left, the predictor of png filter 4."""
    guess = left + up - up_left
    to_left, to_up, to_up_left = abs(guess - left), abs(guess - up), abs(guess - up_left)
    if to_left <= to_up and to_left <= to_up_left:
        return left
    if to_up <= to_up_left:
        return up
    return up_left


def decode_png(data):
    """Decode the 8-bit RGBA, non-interlaced png that rsvg-convert writes, into rows of (r, g, b, a)."""
    width, height = struct.unpack(">II", data[16:24])
    chunks, pos = b"", 8
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        if kind == b"IDAT":
            chunks += data[pos + 8:pos + 8 + length]
        pos += 12 + length
    raw, stride, rows, previous = zlib.decompress(chunks), width * 4, [], bytearray(width * 4)
    for y in range(height):
        start = y * (stride + 1)
        kind, line = raw[start], bytearray(raw[start + 1:start + 1 + stride])
        for i in range(stride):
            left = line[i - 4] if i >= 4 else 0
            up = previous[i]
            up_left = previous[i - 4] if i >= 4 else 0
            if kind == 1:
                line[i] = (line[i] + left) & 0xFF
            elif kind == 2:
                line[i] = (line[i] + up) & 0xFF
            elif kind == 3:
                line[i] = (line[i] + (left + up) // 2) & 0xFF
            elif kind == 4:
                line[i] = (line[i] + paeth(left, up, up_left)) & 0xFF
        rows.append([tuple(line[x * 4:x * 4 + 4]) for x in range(width)])
        previous = line
    return rows


def braille_logo(svg_path, gap_colors):
    bird, wordmark = open(svg_path).read().split('id="wordmark"')
    svg = bird + 'id="wordmark"' + re.sub(r'(fill[=:]"?)#[0-9A-Fa-f]{6}', r"\g<1>" + BIRD_BLUE, wordmark)
    palette = {tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) for h in re.findall(r'#([0-9A-Fa-f]{6})"', svg)}
    png = subprocess.run(["rsvg-convert", "-w", str(WIDTH)], input=svg.encode(), check=True, capture_output=True).stdout
    pixels = decode_png(png)
    height = len(pixels)
    lines = []
    for y in range(0, height, 4):
        line, current = "", None
        for x in range(0, WIDTH, 2):
            dots, colors = 0, collections.Counter()
            for row in range(4):
                for column in range(2):
                    if y + row >= height:
                        continue
                    pixel = pixels[y + row][x + column]
                    if pixel[3] < 0x80:
                        continue
                    snapped = min(palette, key=lambda p: sum((a - b) ** 2 for a, b in zip(pixel[:3], p)))
                    if snapped in gap_colors:
                        continue
                    dots |= BRAILLE_DOTS[row][column]
                    colors[snapped] += 1
            if not colors:
                line += " "
                continue
            color = colors.most_common(1)[0][0]
            if color != current:
                line += "\\033[38;2;%d;%d;%dm" % color
                current = color
            line += chr(0x2800 + dots)
        line = line.rstrip()
        if current is not None:
            line += "\\033[0m"
        lines.append(line)
    return "\n".join(lines).strip("\n")


path = sys.argv[1]
generated = "".join(f"{name}='\n{braille_logo(*logo)}\n'\n" for name, logo in LOGOS.items())
script = open(path).read()
begin, end = "# BEGIN banner, generated by scripts/banner.py\n", "# END banner\n"
script = re.sub(re.escape(begin) + ".*?" + re.escape(end), lambda _: begin + generated + end, script, flags=re.S)
open(path, "w").write(script)
